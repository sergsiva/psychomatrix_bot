def format_pretty_matrix(matrix):
    """Форматирует матрицу в красивую таблицу с эмодзи"""
    m = matrix
    
    # Тройные линии для красоты
    return f"""
┏━━━━━━━┳━━━━━━━┳━━━━━━━┓
┃   {m.get(1, 0)}   ┃   {m.get(4, 0)}   ┃   {m.get(7, 0)}   ┃
┣━━━━━━━╋━━━━━━━╋━━━━━━━┫
┃   {m.get(2, 0)}   ┃   {m.get(5, 0)}   ┃   {m.get(8, 0)}   ┃
┣━━━━━━━╋━━━━━━━╋━━━━━━━┫
┃   {m.get(3, 0)}   ┃   {m.get(6, 0)}   ┃   {m.get(9, 0)}   ┃
┗━━━━━━━┻━━━━━━━┻━━━━━━━┛
"""

def format_matrix_with_headers(matrix):
    """Форматирует матрицу с подписями строк"""
    m = matrix
    return f"""
┌─────────────────────────────────┐
│         МАТРИЦА СУДЬБЫ          │
├─────────┬─────────┬─────────────┤
│ ХАРАКТЕР│ ЗДОРОВЬЕ│    УДАЧА    │
│    {m.get(1, 0)}    │    {m.get(4, 0)}    │     {m.get(7, 0)}     │
├─────────┼─────────┼─────────────┤
│ ЭНЕРГИЯ │ ЛОГИКА  │    ДОЛГ     │
│    {m.get(2, 0)}    │    {m.get(5, 0)}    │     {m.get(8, 0)}     │
├─────────┼─────────┼─────────────┤
│ ИНТЕРЕС │  ТРУД   │   ПАМЯТЬ    │
│    {m.get(3, 0)}    │    {m.get(6, 0)}    │     {m.get(9, 0)}     │
└─────────┴─────────┴─────────────┘
"""

def format_short_matrix(matrix):
    """Краткий формат для списка"""
    m = matrix
    return f"[{m.get(1,0)}-{m.get(2,0)}-{m.get(3,0)}] [{m.get(4,0)}-{m.get(5,0)}-{m.get(6,0)}] [{m.get(7,0)}-{m.get(8,0)}-{m.get(9,0)}]"